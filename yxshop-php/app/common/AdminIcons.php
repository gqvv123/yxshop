    /** @var array<string, true>|null */
    private static ?array $lookup = null;

    /**
     * 返回可直接渲染的图标名；留空或不在图标库里时回退到通用图标。
     */
    public static function normalize($icon): string
    {
        $icon = strtolower(trim((string) $icon));
        if ($icon === '') {
            return self::FALLBACK;
        }
        if (self::$lookup === null) {
            self::$lookup = array_fill_keys(self::AVAILABLE, true);
        }
        return isset(self::$lookup[$icon]) ? $icon : self::FALLBACK;
    }
